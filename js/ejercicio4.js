// Declaramos los lados del rectángulo
const base = 15;
const altura = 7;

// Calculamos área y perímetro
const area = base * altura;
const perimetro = 2*base + 2*altura;

// Mostramos los resultados con template strings
console.log(`Base: ${base} cm | Altura: ${altura} cm`);
console.log(`Área: ${area} cm²`);
console.log(`Perímetro: ${perimetro} cm`);